import {chromium,expect} from '@playwright/test';
const browser=await chromium.launch();
try{for(const width of [390,1440]){
 const page=await browser.newPage({viewport:{width,height:950}});
 const items=[{id:'a',number:1,name:'My experiment',configuration:{waves:10},running:null,latest:{run_tag:'a',configuration:{waves:10}},progress:{iteration:2}},{id:'b',number:2,name:'Waiting for hypothesis',configuration:{waves:10},running:null,latest:null,progress:{}}];
 let events=[];
 const hypothesis='Blood pressure and exercise predict the recorded outcome. '.repeat(5);
 await page.route('**/control/**',r=>r.fulfill({json:new URL(r.request().url()).pathname==='/control/pipelines'?{pipelines:items}:{}}));
 await page.route('**/api/**',r=>{return r.fulfill({json:new URL(r.request().url()).pathname==='/api/discovery/live'?{events,questions:[],results:[{result_id:1,trial:1,iteration:2,run_tag:'a',hypothesis},{result_id:2,trial:1,run_tag:'unrelated',hypothesis:'Unrelated finding'}],reports:{},generated_at:new Date().toISOString(),record_limit:200}:{}});});
 await page.goto(process.env.MEMSTARA_TEST_URL||'http://127.0.0.1:4175');
 await page.getByRole('navigation').getByRole('button',{name:'Experiments',exact:true}).first().click();
 const show=page.getByRole('button',{name:'Show pipeline list',exact:true});if(await show.isVisible())await show.click();
 const first=page.getByRole('button',{name:'Inspect My experiment',exact:true});
 await expect(first.locator('.pipeline-card-name')).toContainText('Blood pressure and exercise',{timeout:25000});
 await expect(first.locator('.pipeline-card-name')).not.toHaveAttribute('title');
 await expect(first.locator('.pipeline-card-name')).toHaveAttribute('aria-label',hypothesis.trim());
 await expect.poll(()=>first.locator('.pipeline-card-name').evaluate(e=>e.getBoundingClientRect().height<=parseFloat(getComputedStyle(e).lineHeight)*2+1)).toBe(true);
 const heading=first.locator('.pipeline-card-name');
 const before=await first.boundingBox();
 await heading.hover();
 const popup=page.locator('.hypothesis-popup');
 await expect(popup).toBeVisible();
 await expect(popup.locator('p')).toHaveText(hypothesis.trim());
 await expect.poll(async()=>Math.abs((await first.boundingBox()).height-before.height)).toBeLessThan(1);
 await expect.poll(async()=>{const b=await popup.boundingBox();return b.x>=0&&b.x+b.width<=width+1&&b.y>=0&&b.y+b.height<=951;}).toBe(true);
 await expect.poll(()=>popup.evaluate(e=>getComputedStyle(e).opacity)).toBe('1');
 await popup.hover();
 await expect(popup).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(popup).toHaveCount(0);
 await page.mouse.move(0,0);
 await page.keyboard.press('Tab');
 await heading.focus();
 await expect(popup).toBeVisible();
 await page.keyboard.press('Escape');
 await heading.evaluate(e=>e.blur());
 await expect(first).toContainText('Saved as: My experiment');
 await expect(first).not.toContainText('Unrelated finding');
 await expect(page.getByRole('button',{name:'Inspect Waiting for hypothesis',exact:true}).locator('.pipeline-card-name')).toHaveText('Waiting for hypothesis');
 await expect(first.locator('.pipeline-card-position')).toContainText('Replicate');
 await expect.poll(()=>first.evaluate(e=>e.scrollWidth<=e.clientWidth+1)).toBe(true);
 items[0].running={run_tag:'a',configuration:{waves:10,trials:1}};
 items[0].progress={iteration:3,stage:'hypothesis'};
 await expect(first.locator('.pipeline-card-name')).toHaveText('Generating hypothesis…',{timeout:25000});
 events=[{id:'h3',revision:'1',run_tag:'a',stage:'hypothesis',detail:'Current replicate hypothesis',iteration:3,trial:2,at:new Date().toISOString()}];
 await expect(first.locator('.pipeline-card-name')).toHaveText('Current replicate hypothesis',{timeout:25000});
 await expect(first).not.toContainText('Blood pressure and exercise');
 await expect(first.locator('.pipeline-card-name')).toHaveAttribute('aria-label','Current replicate hypothesis');
 await first.locator('.pipeline-card-name').hover();
 await expect(page.locator('.hypothesis-popup p')).toHaveText('Current replicate hypothesis');
 await page.close();
}}finally{await browser.close();}
