import { Calculator, Sparkles } from 'lucide-react';
import './report-transparency.css';

export type ContentOriginKind = 'llm' | 'mixed' | 'proposal' | 'rule';
const origins = {
  llm: ['LLM interpretation', 'Qualitative interpretation by an LLM; not a calculated score or validated conclusion.'],
  mixed: ['LLM text + recorded data', 'Narrative judgments are generated by an LLM. Quoted measurements and execution records must be checked against their source.'],
  proposal: ['Agent research proposal', 'A proposed question or hypothesis, not an established finding. Review its recorded source and rationale.'],
  rule: ['System rule', 'This message is derived from recorded metrics or a fixed code rule, not an LLM assessment.'],
} as const;

export default function ContentOrigin({kind, compact = false}: {kind: ContentOriginKind; compact?: boolean}) {
  const [label, detail] = origins[kind];
  const Icon = kind === 'rule' ? Calculator : Sparkles;
  return <span className={`content-origin ${compact ? 'is-compact' : ''}`} data-content-origin={kind}
    data-assessment-kind={kind === 'rule' ? 'measured' : 'judgment'} title={detail}>
    <span className="assessment-badge"><Icon size={12} aria-hidden="true"/>{label}</span>
    {!compact && <span className="content-origin-detail">{detail}</span>}
  </span>;
}
