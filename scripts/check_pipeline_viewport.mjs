import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_PATH});
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://localhost:8070');
  await page.getByRole('button',{name:'Readable',exact:true}).waitFor({timeout:60000});
  await page.locator('.react-flow__node-pipelineStage').first().waitFor();
  assert.equal(await page.locator('.react-flow__node-pipelineStage').count(), 5);
  await page.getByRole('button',{name:'Readable',exact:true}).click();
  await page.waitForTimeout(400);
  const transform=()=>page.locator('.react-flow__viewport').first().getAttribute('style');
  assert((await transform()).includes('scale(1)'));
  const card=await page.locator('.react-flow__node-chain').first().boundingBox();
  assert(card.width>=220, `card width ${card.width}`);
  await page.getByRole('button',{name:'Expand',exact:true}).click();
  await page.getByRole('combobox',{name:'Focus pipeline stage'}).selectOption('report');
  await page.waitForTimeout(500);
  const reportCard = page.locator('.react-flow__node-chain [role=group]').last();
  await reportCard.focus();
  await reportCard.press('Enter');
  await page.getByRole('button', {name:'Close agent details',exact:true}).waitFor();
  await page.getByRole('button', {name:'Close agent details',exact:true}).click();
  const before=await transform();
  await page.waitForTimeout(4500);
  assert.equal(await transform(), before, 'polls must not reset the viewport');
  await page.getByRole('button',{name:'Fit all',exact:true}).click();
  await page.waitForTimeout(400);
  const topCard = await page.locator('.react-flow__node-chain').first().boundingBox();
  const toolbar = await page.getByRole('button',{name:'Readable',exact:true}).boundingBox();
  assert(topCard.y > toolbar.y + toolbar.height, 'Fit all must keep cards below the toolbar');
  await page.screenshot({path:'/tmp/pipeline-expanded.png'});
  await page.getByRole('button',{name:'Readable',exact:true}).click();
  await page.getByRole('button',{name:'Zoom in',exact:true}).click();
  await page.waitForTimeout(400);
  assert(!(await transform()).includes('scale(1)'));
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Expand',exact:true}).waitFor();
  const savedTag = await page.locator('select').first().inputValue();
  await page.locator('select').first().selectOption('');
  const interpreters=page.locator('.react-flow__node-chain [role="group"][aria-label^="Interpreter:"]');
  const initial=await interpreters.count();
  await page.getByRole('button',{name:'Fit all',exact:true}).click();
  await page.getByRole('button',{name:'Add interpreter agent',exact:true}).click();
  const dialog=page.locator('dialog[open]');
  const skill=await dialog.locator('select option').evaluateAll(options => options.find(o => o.value && !o.disabled).value);
  await dialog.locator('select').selectOption(skill);
  await dialog.getByRole('button',{name:'Add interpreter',exact:true}).click();
  await page.waitForTimeout(350);
  assert.equal(await interpreters.count(), initial+1);
  await page.getByRole('combobox',{name:'Focus pipeline stage'}).selectOption('interpreter');
  await page.waitForTimeout(350);
  await page.locator('.react-flow__node-chain button[aria-label="Remove interpreter 1"]').click();
  await page.waitForTimeout(350);
  assert.equal(await interpreters.count(), initial);
  assert((await interpreters.allTextContents()).some(text => text.includes(skill)));
  if(initial===1) assert.equal(await page.locator('.react-flow__node-chain button[aria-label^="Remove interpreter"]').count(),0);
  await page.reload();
  await page.getByRole('button',{name:'Readable',exact:true}).waitFor();
  await page.waitForTimeout(1500);
  assert.equal(await page.locator('select').first().inputValue(), '');
  assert.equal(await interpreters.count(), initial, 'deleted agent must not return on refresh');
  assert((await interpreters.allTextContents()).some(text => text.includes(skill)));
  if(savedTag) {
    await page.locator('select').first().selectOption(savedTag);
    await page.waitForFunction(() => !document.body.innerText.includes('Loading the pipeline'));
    await page.waitForTimeout(1500);
    await page.locator('select').first().selectOption('');
    await page.waitForTimeout(300);
    assert.equal(await interpreters.count(), initial, 'viewing a saved run must not overwrite the draft');
    assert((await interpreters.allTextContents()).some(text => text.includes(skill)));
  }
  for (let count = await interpreters.count(); count < 4; count++) {
    await page.getByRole('button',{name:'Fit all',exact:true}).click();
    await page.waitForTimeout(400);
    await page.getByRole('button',{name:'Add interpreter agent',exact:true}).click();
    const nextSkill = await dialog.locator('select option').evaluateAll(options => options.find(o => o.value && !o.disabled).value);
    await dialog.locator('select').selectOption(nextSkill);
    await dialog.getByRole('button',{name:'Add interpreter',exact:true}).click();
    await page.waitForTimeout(350);
    assert.equal(await interpreters.count(), count + 1);
  }
  assert(await page.getByRole('button',{name:'Add interpreter agent',exact:true}).isDisabled());
  await page.getByRole('button',{name:'Fit all',exact:true}).click();
  await page.waitForTimeout(400);
  await page.screenshot({path:'/tmp/pipeline-interpreter-add.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: readable 224px cards, expand/restore, stage navigation, fit, zoom, polling stability; canvas interpreter addition, distinct skills, deletion, persistence and maximum of four; no analysis started.');
} finally { await browser.close(); }
